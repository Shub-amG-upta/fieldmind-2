"""
Writes configs/tep.yaml: the TEP overlay on configs/base.yaml.

Every L1 threshold is FITTED to the FAULT-FREE training runs only
(data/reference/tep/fingerprint.json, by data/tep/fingerprint.py), with the
same rules as the Cranfield pack (data/cranfield/calibrate.py):

  rates      threshold = p99.7 of the healthy |OLS slope| over the rate window
             (10 samples = 30 min), direction abs, severity WATCH
  limits     alarm_lo / alarm_hi = p0.1 / p99.9 of the healthy values, ALARM
  bands      [p85, p99.7, max] of the healthy |slope| over the signature window
             (20 samples = 60 min)
  validity   frozen = exactly constant over 60 min (tolerance 1e-12; no tag is
             ever exactly constant that long on healthy data); physical range
             [0, 100] for unit "%" (valves, levels: definition) -- NOT for mol%,
             whose healthy readings go slightly negative (measurement noise,
             e.g. product D p0.1 = -0.012); otherwise unbounded; max_step off

Window lengths (DESIGN, DESIGN-range in reports/b2_tep_pack.md): one sample
per 3 min, so the boiler's 3-10 min windows would hold 1-3 samples.

    python -m data.tep.calibrate
"""

from __future__ import annotations

import json

from .convert import REF, ROOT, TAGS, TICK_PERIOD_S

FP = REF / "fingerprint.json"
OUT = ROOT / "configs/tep.yaml"
UNBOUNDED = 1.0e9
RATE_MIN, SIG_MIN, FROZEN_MIN, VAR_MIN = 30.0, 60.0, 60.0, 60.0
# DESIGN (accuracy-fixes step 2a, pre-registered; range 2-4): a DEVIATION/ALARM is published
# after 3 consecutive ticks. Costs 2 ticks (6 min) of detection delay.
PERSIST = 3
# Accuracy-fixes step 2b (pre-registered): limits, rates and variability at the Sidak-corrected
# healthy quantiles (fingerprint "joint": family-wise 1 % of healthy ticks over 52 tags x 3 kinds)
# instead of the per-tag p0.1/p99.9/p99.7. False = the per-tag rule (B2). Bands unchanged.
# REVERTED on dev (reports/accuracy_fixes.md step 2b): detection -0.077, accuracy -0.013.
JOINT = False


def _lit(x: float) -> str:
    """A YAML float literal. PyYAML (YAML 1.1) reads 1e-12, with no decimal
    point, as a STRING; give every exponent form a mantissa with a point."""
    r = repr(float(x))
    if "e" in r and "." not in r.split("e")[0]:
        m, e = r.split("e")
        r = f"{m}.0e{e}"
    return r


def _g(x: float) -> str:
    return _lit(float(f"{x:.4g}"))


def build() -> str:
    fp = json.loads(FP.read_text())
    T = fp["tags"]
    assert fp["windows_samples"] == {"rate": int(RATE_MIN / 3), "signature": int(SIG_MIN / 3),
                                     "frozen": int(FROZEN_MIN / 3), "variability": int(VAR_MIN / 3)}, \
        "fingerprint windows differ"
    L = ["# GENERATED by `python -m data.tep.calibrate` from data/reference/tep/fingerprint.json",
         "# (TEP fault-free training runs only). Do not edit by hand. Method: data/tep/calibrate.py.",
         "# Overlay: run_demo.py --overlay configs/v3.yaml,configs/tep.yaml --episodes-dir data/episodes_tep_dev",
         "asset: tep", "",
         "agent:",
         f"  tick_period_s: {TICK_PERIOD_S}            # one assessment per 3-min sample",
         f"  state_persistence_ticks: {PERSIST}       # accuracy-fixes step 2a, reports/accuracy_fixes.md", "",
         "paths:",
         "  asset_model: data/kb_tep/asset_model.json",
         "  case_library: data/kb_tep/case_library.json",
         "  action_catalogue: data/kb_tep/action_catalogue.json",
         "  episodes: data/episodes_tep",
         "  experience: data/kb_tep/experience.json", "",
         "multi:",
         "  case_groups: data/kb_tep/case_groups.json",
         "  # The in-place mutation audit fingerprints every section after every step; the event",
         "  # timeline only grows, so on 960-tick episodes it took 98 % of run time (profiled).",
         "  # Off for TEP only; the single-writer API check stays on, and the audit stays on for",
         "  # the boiler, Cranfield and the tests (same agent code). reports/b2_tep_pack.md.",
         "  audit_writes: false",
         "  fixed_placement: {diag_reaction: npu, diag_separation: npu}", "",
         "checks:",
         "  sample_period_s: 180.0",
         f"  signature_window_min: {SIG_MIN}",
         "  balance: {window_min: 30.0}     # no balance family (as Cranfield)",
         "  rates_long: {}",
         "  limits:"]
    lo = {t: T[t]["joint"]["lo"] if JOINT else T[t]["p0_1"] for t in TAGS}
    hi = {t: T[t]["joint"]["hi"] if JOINT else T[t]["p99_9"] for t in TAGS}
    rate = {t: T[t]["joint"]["rate"] if JOINT else T[t]["rate_slope_abs_p99_7"] for t in TAGS}
    var = {t: T[t]["joint"]["var"] if JOINT else T[t]["step_sd_60min_p99_7"] for t in TAGS}
    for t in TAGS:
        L += [f"    {t}:",
              f"      alarm_lo: {{op: \"<\", value: {_g(lo[t])}, severity: ALARM}}",
              f"      alarm_hi: {{op: \">\", value: {_g(hi[t])}, severity: ALARM}}"]
    L.append("  rates:")
    for t in TAGS:
        L.append(f"    {t}: {{threshold: {_g(rate[t])}, sustained_min: {RATE_MIN}, "
                 f"direction: abs, unit: \"{T[t]['unit']}/min\", severity: WATCH}}")
    # TEP variability check (fieldmind/assets/tep.py): fact when the sd of the
    # sample-to-sample changes over VAR_MIN exceeds the healthy p99.7
    L += ["  variability:", f"    window_min: {VAR_MIN}", "    thresholds:"]
    for t in TAGS:
        L.append(f"      {t}: {_g(var[t])}")
    L.append("  bands:")
    for t in TAGS:
        s = T[t]["sig_slope_abs"]
        L.append(f"    {t}: [{_g(s['p85'])}, {_g(s['p99_7'])}, {_g(s['max'])}]")
    L += ["  validity:", f"    stuck_minutes: {FROZEN_MIN}", "    stuck_mad_eps:"]
    for t in TAGS:
        L.append(f"      {t}: {_lit(0.0 if T[t]['ever_constant_60min'] else 1.0e-12)}")
    L.append("    physical_range:")
    for t in TAGS:
        rng = [0.0, 100.0] if T[t]["unit"] == "%" else [-UNBOUNDED, UNBOUNDED]
        L.append(f"      {t}: [{_lit(rng[0])}, {_lit(rng[1])}]")
    L.append("    max_step:")
    for t in TAGS:
        L.append(f"      {t}: {_lit(UNBOUNDED)}")
    return "\n".join(L) + "\n"


def numeric_problems(cfg: dict) -> list[str]:
    c, bad = cfg["checks"], []
    for tag, v in c["limits"].items():
        bad += [f"limits.{tag}" for x in v.values() if not isinstance(x["value"], float)]
    bad += [f"rates.{t}" for t, v in c["rates"].items() if not isinstance(v["threshold"], float)]
    bad += [f"bands.{t}" for t, v in c["bands"].items()
            if not all(isinstance(x, float) for x in v) or not v[0] <= v[1] <= v[2]]
    bad += [f"stuck.{t}" for t, x in c["validity"]["stuck_mad_eps"].items() if not isinstance(x, float)]
    bad += [f"variability.{t}" for t, x in c["variability"]["thresholds"].items()
            if not isinstance(x, float) or x <= 0]
    return bad


def main() -> None:
    import yaml
    text = build()
    bad = numeric_problems(yaml.safe_load(text))
    if bad:
        raise SystemExit(f"bad thresholds in the generated YAML: {bad[:5]}")
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
