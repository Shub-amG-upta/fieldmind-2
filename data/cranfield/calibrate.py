"""
Writes configs/cranfield.yaml: the Cranfield overlay on configs/base.yaml.

Every L1 threshold is FITTED to the NORMAL sets only
(data/reference/cranfield/fingerprint.json, built from T1-T3 by
data/cranfield/fingerprint.py). No fault data set is read here. The fitting
rules mirror the boiler's (configs/base.yaml comments, stage 4 and session 1b):

  rates      threshold = p99.7 of the healthy 5-min |OLS slope| (boiler: "every
             threshold below is set from the p99.7 of the matching statistic"),
             sustained 5 min, direction abs, severity WATCH
  limits     alarm_lo / alarm_hi = p0.1 / p99.9 of the healthy values (the rig
             publishes no alarm limits for this configuration), severity ALARM
  bands      [deadband, slow/med, med/fast] = [p85, p99.7, max] of the healthy
             10-min |slope| (session 1b: deadband = p85 of healthy 10-min slope;
             FAST = faster than anything seen in normal operation)
  validity   "frozen" = the reading does not change at all over 3 min (MAD below
             1e-12, i.e. exactly constant), DERIVED from the meaning of the check;
             off (0) for the tags that sit exactly constant on healthy data. (A
             first version fitted 0.5 x the smallest healthy 3-min MAD: on dev set
             6.1 the water-density meter, varying normally (86 distinct values,
             MAD 1.8e-4), read as frozen on every tick. Decision on dev, recorded
             in reports/b1_cranfield_pack.md.) Physical range [0, 100] for % tags (definition), otherwise
             unbounded (no instrument spans published); max_step off (abrupt
             faults, e.g. case 6, must not be mistaken for instrument steps)

    python -m data.cranfield.calibrate
"""

from __future__ import annotations

import json

from .convert import ROOT, TAGS

FP = ROOT / "data/reference/cranfield/fingerprint.json"
OUT = ROOT / "configs/cranfield.yaml"
UNBOUNDED = 1.0e9
# DESIGN (accuracy-fixes step 2a, pre-registered; range 2-4): a DEVIATION/ALARM is published
# after 3 consecutive ticks. Costs 2 ticks (1 min) of detection delay.
PERSIST = 3
# Accuracy-fixes step 2b (pre-registered): limits and rates at the Sidak-corrected healthy
# quantiles (fingerprint "joint": family-wise 1 % of healthy ticks over 24 tags x 2 kinds; rates
# fall back to the healthy max, too few 5-min windows). False = the per-tag rule (B1). Bands unchanged.
# REVERTED on dev (reports/accuracy_fixes.md step 2b): false alarms before the fault did not drop.
JOINT = False


def _g(x: float) -> float:
    return float(f"{x:.4g}")


def build() -> str:
    fp = json.loads(FP.read_text())["tags"]
    L = ["# GENERATED by `python -m data.cranfield.calibrate` from",
         "# data/reference/cranfield/fingerprint.json (normal sets T1-T3 only). Do not edit by hand.",
         "# Overlay on configs/base.yaml: run_demo.py --overlay configs/cranfield.yaml",
         "#   --episodes-dir data/episodes_cranfield_dev",
         "# Method of every number: data/cranfield/calibrate.py docstring. Asset: fieldmind/assets/cranfield.py.",
         "asset: cranfield", "",
         "agent:",
         f"  state_persistence_ticks: {PERSIST}       # accuracy-fixes step 2a, reports/accuracy_fixes.md", "",
         "paths:",
         "  asset_model: data/kb_cranfield/asset_model.json",
         "  case_library: data/kb_cranfield/case_library.json",
         "  action_catalogue: data/kb_cranfield/action_catalogue.json",
         "  episodes: data/episodes_cranfield",
         "  experience: data/kb_cranfield/experience.json", "",
         "multi:",
         "  case_groups: data/kb_cranfield/case_groups.json",
         "  fixed_placement: {diag_supply: npu, diag_process: npu}", "",
         "checks:",
         "  sample_period_s: 1.0",
         "  balance: {window_min: 5.0}      # no balance family (HUMAN DECISION 2026-11-05)",
         "  rates_long: {}",
         "  limits:"]
    for t in TAGS:
        r = fp[t]
        L.append(f"    {t}:")
        lo, hi = (r["joint"]["lo"], r["joint"]["hi"]) if JOINT else (r["p0_1"], r["p99_9"])
        L.append(f"      alarm_lo: {{op: \"<\", value: {_g(lo)}, severity: ALARM}}")
        L.append(f"      alarm_hi: {{op: \">\", value: {_g(hi)}, severity: ALARM}}")
    L.append("  rates:")
    for t in TAGS:
        r = fp[t]
        L.append(f"    {t}: {{threshold: {_g(r['joint']['rate'] if JOINT else r['slope_abs']['5min']['p99_7'])}, sustained_min: 5.0, "
                 f"direction: abs, unit: \"{r['unit']}/min\", severity: WATCH}}")
    L.append("  bands:")
    for t in TAGS:
        s = fp[t]["slope_abs"]["10min"]
        L.append(f"    {t}: [{_g(s['p85'])}, {_g(s['p99_7'])}, {_g(s['max'])}]")
    L.append("  validity:")
    L.append("    stuck_minutes: 3.0")
    L.append("    stuck_mad_eps:")
    for t in TAGS:
        L.append(f"      {t}: {0.0 if fp[t]['mad_3min_min'] == 0 else '1.0e-12'}")
    L.append("    physical_range:")
    for t in TAGS:
        rng = [0.0, 100.0] if fp[t]["unit"] == "%" else [-UNBOUNDED, UNBOUNDED]
        L.append(f"      {t}: [{rng[0]}, {rng[1]}]")
    L.append("    max_step:")
    for t in TAGS:
        L.append(f"      {t}: {UNBOUNDED}")
    return "\n".join(L) + "\n"


def _all_numbers(cfg: dict) -> list[str]:
    """Paths of threshold leaves that YAML did not read as numbers (PyYAML reads
    1e-12 without a decimal point as a string)."""
    bad = []
    c = cfg["checks"]
    for sec in ("limits", "rates", "bands"):
        for tag, v in c[sec].items():
            vals = ([x["value"] for x in v.values()] if sec == "limits" else
                    [v["threshold"]] if sec == "rates" else list(v))
            bad += [f"{sec}.{tag}" for x in vals if not isinstance(x, (int, float))]
    for sec in ("stuck_mad_eps", "max_step"):
        bad += [f"validity.{sec}.{t}" for t, x in c["validity"][sec].items()
                if not isinstance(x, (int, float))]
    return bad


def main() -> None:
    import yaml
    text = build()
    bad = _all_numbers(yaml.safe_load(text))
    if bad:
        raise SystemExit(f"non-numeric thresholds in the generated YAML: {bad[:5]}")
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
